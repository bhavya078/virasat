export function translateStateName(stateName: string, langCode: string): string {
  if (!stateName || langCode === 'en') return stateName;
  const match = STATE_TRANSLATIONS[stateName];
  if (match && match[langCode]) {
    return match[langCode];
  }
  // Try partial match
  for (const [key, val] of Object.entries(STATE_TRANSLATIONS)) {
    if (stateName.toLowerCase().includes(key.toLowerCase()) && val[langCode]) {
      return val[langCode];
    }
  }
  return stateName;
}

